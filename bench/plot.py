#!/usr/bin/env python3
"""Turn results/calibration.json into figures and results/SUMMARY.md."""
import json
import os
import statistics
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src))
os.makedirs(out, exist_ok=True)
PAIRED, NAIVE, SEQ = "#2bb3a3", "#9aa5b1", "#e8a33d"


def short(f):
    f = f.replace("_gpt-4.1-2025-04-14_4trials.json", "")
    for a, b in [("claude-3-7-sonnet-20250219", "claude-3.7"), ("gpt-4.1-mini-2025-04-14", "gpt-4.1-mini"),
                 ("gpt-4.1-2025-04-14", "gpt-4.1"), ("o4-mini-2025-04-16", "o4-mini")]:
        f = f.replace(a, b)
    return f


md = ["# AgentGate calibration results", "",
      "Generated by `bench/plot.py` from `results/calibration.json` (`agentgate calibrate`, 400 resamples per experiment).",
      "Data: the 26 published tau2-bench result files (4 agent models; airline, retail, telecom and telecom variants; 4 trials per task; "
      "user simulator gpt-4.1). Nothing here called a model: every number is a resample or reanalysis of trials that already exist.",
      f"Gate settings: one-sided alpha {d['alpha']}, FAIL when the 90% CI is entirely below -{100*d['fail_margin']:.0f} points, "
      f"PASS when it is entirely above -{100*d['pass_margin']:.0f} points, else INCONCLUSIVE.", ""]

# ---- A/A
aa = d["aa"]
fp = [a["false_fail_paired"] for a in aa]
fn = [a["false_fail_naive"] for a in aa]
md += ["## 1. A/A: false alarms when nothing changed", "",
       "Each file's 4 trials per task split at random into 2 + 2, 400 times. Same agent on both sides, so every FAIL is a false alarm.", "",
       f"- Paired, task-clustered t-test: mean false-FAIL rate **{100*statistics.mean(fp):.1f}%** across {len(aa)} files "
       f"(range {100*min(fp):.1f} to {100*max(fp):.1f}%; target 5%, binomial SE at 400 resamples is 1.1 points).",
       f"- Naive unpaired two-proportion z-test: mean {100*statistics.mean(fn):.1f}% (range {100*min(fn):.1f} to {100*max(fn):.1f}%). "
       "It is conservative here, not flaky: pairing removes the shared per-task difficulty, so the naive test overstates the variance. "
       "The price is power (section 3).",
       f"- With only 2 trials per side the gate PASSed an unchanged agent in {100*statistics.mean(a['pass_paired'] for a in aa):.0f}% of splits on average; "
       "the rest were INCONCLUSIVE. That is the gate saying 2 trials is not enough to clear a 5-point margin, which section 4 quantifies.", "",
       "| file | tasks | pass^1 | false FAIL paired | false FAIL naive | PASS paired |", "|---|---|---|---|---|---|"]
for a in aa:
    md.append(f"| {short(a['file'])} | {a['tasks']} | {a['pass_rate']:.2f} | {100*a['false_fail_paired']:.1f}% | {100*a['false_fail_naive']:.1f}% | {100*a['pass_paired']:.0f}% |")
md.append("")

# ---- swaps
md += ["## 2. Real model swaps (full 4-trial data)", "",
       "The candidate is gpt-4.1-mini in every row. 'Detected at k' re-runs the gate on 400 bootstrap resamples of tasks using only the first k trials; "
       "it is power at the observed effect, so it is optimistic for effects near the threshold.", "",
       "| baseline -> gpt-4.1-mini | suite | pass^1 A | pass^1 B | verdict | 90% CI (points) | detected k=1 | k=2 | k=4 | naive k=4 |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for s in d["swaps"]:
    a = s["pair"].split(" -> ")[0].split("/")[0]
    fr, nf = s["fail_rate_by_trials"], s["naive_fail_rate_by_trials"]
    md.append(f"| {short(a)} | {s['suite']} | {s['rate_a']:.3f} | {s['rate_b']:.3f} | {s['verdict_full_data']} | "
              f"{100*s['ci_low']:+.1f} to {100*s['ci_high']:+.1f} | {100*fr['1']:.0f}% | {100*fr['2']:.0f}% | {100*fr['4']:.0f}% | {100*nf['4']:.0f}% |")
md += ["", "gpt-4.1-mini is *better* than gpt-4.1 on telecom (PASS, interval entirely above zero), so 'smaller model' is not a guaranteed regression; "
       "the gate measures, it does not assume.", ""]

# ---- injections
inj = d["injections"]
md += ["## 3. Injected regressions (gpt-4.1, 2 trials per side)", "",
       "A and B are disjoint 2-trial halves of the same run; B is degraded by flipping passing trials of affected tasks to failures. "
       "Tool-family injections pick tasks whose reference solution calls that tool family (from tau2-bench evaluation criteria).", "",
       "| suite | injection | affected tasks | true drop (points) | detected, paired | detected, naive | sequential (K=2) | mean trials/task, sequential |",
       "|---|---|---|---|---|---|---|---|"]
for i in inj:
    suite = "retail" if "retail" in i["file"] else "airline"
    md.append(f"| {suite} | {i['injection']} | {i['affected_tasks']:.0f} | {i['true_drop_points']:.1f} | {100*i['power_paired']:.0f}% | "
              f"{100*i['power_naive']:.0f}% | {100*i['sequential_power']:.0f}% | {i['sequential_mean_trials_per_task']:.2f} of 2 |")
md.append("")

fig, ax = plt.subplots(figsize=(8, 3.6))
labels = [("retail: " if "retail" in i["file"] else "airline: ") + i["injection"].split(":")[0].split(" (")[0] + f" ({i['true_drop_points']:.1f} pts)" for i in inj]
y = list(range(len(inj)))
ax.barh([v + 0.2 for v in y], [100 * i["power_paired"] for i in inj], 0.4, color=PAIRED, label="paired, task-clustered")
ax.barh([v - 0.2 for v in y], [100 * i["power_naive"] for i in inj], 0.4, color=NAIVE, label="naive unpaired")
ax.set_yticks(y, labels, fontsize=8)
ax.invert_yaxis()
ax.set_xlabel("regressions caught (%), 2 trials per side, 400 resamples")
ax.set_xlim(0, 100)
ax.legend(frameon=False, fontsize=8, loc="lower right")
ax.spines[["top", "right"]].set_visible(False)
fig.tight_layout()
fig.savefig(os.path.join(out, "injection_power.png"), dpi=150)

# ---- power curves
pc = d["power_curves_retail_gpt41"]
fig, axs = plt.subplots(1, 2, figsize=(9, 3.4))
for key, ls in [("drop_10_points_all_tasks", "-"), ("drop_5_points_all_tasks", "--")]:
    c = pc[key]
    ks = [p["trials_per_task"] for p in c]
    lab = key.split("_")[1] + "-point drop"
    axs[0].plot(ks, [100 * p["power_fixed"] for p in c], ls, color=PAIRED, marker="o", label=f"fixed, {lab}")
    axs[0].plot(ks, [100 * p["power_sequential"] for p in c], ls, color=SEQ, marker="s", label=f"sequential, {lab}")
    axs[1].plot(ks, [p["mean_trials_sequential_with_drop"] for p in c], ls, color=SEQ, marker="s", label=f"sequential, {lab}")
c = pc["drop_10_points_all_tasks"]
axs[0].plot(ks, [100 * p["pass_rate_when_nothing_changed"] for p in c], ":", color=NAIVE, marker="^", label="PASS rate, no change")
axs[1].plot(ks, [p["mean_trials_sequential_no_change"] for p in c], ":", color=NAIVE, marker="^", label="sequential, no change")
axs[1].plot(ks, ks, color="#cccccc", lw=1, label="fixed budget")
for a in axs:
    a.set_xscale("log", base=2)
    a.set_xticks(ks, [str(k) for k in ks])
    a.set_xlabel("trials per task (budget)")
    a.spines[["top", "right"]].set_visible(False)
axs[0].set_ylabel("%")
axs[0].set_title("detection power (retail, 114 tasks)", fontsize=9)
axs[1].set_ylabel("trials per task actually run")
axs[1].set_title("trials used by the sequential gate", fontsize=9)
axs[0].legend(frameon=False, fontsize=7)
axs[1].legend(frameon=False, fontsize=7)
fig.tight_layout()
fig.savefig(os.path.join(out, "power_curve.png"), dpi=150)

md += ["## 4. Trial budget: power analysis and sequential stopping", "",
       "Parametric model: each retail task keeps its own pass probability from the gpt-4.1 run (Jeffreys posterior mean), "
       "B loses 5 or 10 points on every task, 400 simulated gates per budget. The sequential gate looks after every trial with "
       "O'Brien-Fleming boundaries for K = budget looks (overall one-sided alpha 0.05).", "",
       "| budget k | 10 pts: power fixed | power sequential | trials used | 5 pts: power fixed | power sequential | trials used | no change: false FAIL fixed | false FAIL seq | PASS fixed | trials used seq |",
       "|---|---|---|---|---|---|---|---|---|---|---|"]
c10, c5 = pc["drop_10_points_all_tasks"], pc["drop_5_points_all_tasks"]
for a, b in zip(c10, c5):
    md.append(f"| {a['trials_per_task']} | {100*a['power_fixed']:.0f}% | {100*a['power_sequential']:.0f}% | {a['mean_trials_sequential_with_drop']:.2f} | "
              f"{100*b['power_fixed']:.0f}% | {100*b['power_sequential']:.0f}% | {b['mean_trials_sequential_with_drop']:.2f} | "
              f"{100*a['false_alarm_fixed']:.1f}% | {100*a['false_alarm_sequential']:.1f}% | {100*a['pass_rate_when_nothing_changed']:.0f}% | {a['mean_trials_sequential_no_change']:.2f} |")
k4 = next(p for p in c10 if p["trials_per_task"] == 4)
k8 = next(p for p in c10 if p["trials_per_task"] == 8)
md += ["", f"- A 10-point regression needs about 4 trials per task for {100*k4['power_fixed']:.0f}% power on 114 tasks. "
       f"Capped at 4, the sequential gate reaches the same power with {k4['mean_trials_sequential_with_drop']:.2f} trials per task on average "
       f"({100*(1-k4['mean_trials_sequential_with_drop']/4):.0f}% fewer); capped at 8, {k8['mean_trials_sequential_with_drop']:.2f} "
       f"({100*(1-k8['mean_trials_sequential_with_drop']/8):.0f}% fewer than a fixed 8).",
       f"- Savings shrink when the effect is near the threshold (5-point drop) or zero: an unchanged agent at a cap of 4 still uses "
       f"{k4['mean_trials_sequential_no_change']:.2f} trials, because clearing a 5-point PASS margin needs the evidence.",
       f"- Clearing that margin is the expensive part: with 4 trials a no-op change PASSes only {100*k4['pass_rate_when_nothing_changed']:.0f}% of the time "
       f"(INCONCLUSIVE otherwise); it takes 8 trials to reach {100*k8['pass_rate_when_nothing_changed']:.0f}%.", ""]

# ---- cost
rel = {r["file"]: r for r in d["reliability"]}
r41 = rel["gpt-4.1-2025-04-14_retail_default_gpt-4.1-2025-04-14_4trials.json"]
cost4 = 4 * r41["tasks"] * r41["agent_cost_usd_per_trial"]
seq_cost = k4["mean_trials_sequential_with_drop"] * r41["tasks"] * r41["agent_cost_usd_per_trial"]
trial_h = 4 * r41["tasks"] * r41["seconds_per_trial"] / 3600
md += ["## 5. Cost and time per gate run (retail, gpt-4.1 agent)", "",
       f"From the trial records: ${r41['agent_cost_usd_per_trial']:.3f} agent cost and {r41['seconds_per_trial']:.0f} s per trial "
       "(user-simulator cost not included). Baseline results are reused from main, so a gate pays for the candidate side only.", "",
       f"- Fixed 4 trials x {r41['tasks']} tasks: ${cost4:.2f} and {trial_h:.1f} trial-hours, about {60*trial_h/32:.0f} minutes wall-clock with 32 sandboxes in parallel.",
       f"- Sequential, capped at 4, on a 10-point regression: ${seq_cost:.2f} on average.",
       "- Replay (`replay/`) makes a grader-only change free: no model or tool calls are made when the tool cassette and the trajectories already exist.", ""]

# ---- reliability
md += ["## 6. Where the variance comes from", "",
       "Share of tasks whose 4 identical trials disagree, and test-retest agreement between trials of the same task (Cohen's kappa averaged over trial pairs). "
       "Kappa collapses when nearly every trial passes (o4-mini no-user-op: 99% pass, kappa near 0), so read the mixed-task share first.", "",
       "| file | tasks | pass^1 | pass^4 | tasks with mixed outcomes | test-retest kappa | $/trial | s/trial |", "|---|---|---|---|---|---|---|---|"]
for r in d["reliability"]:
    md.append(f"| {short(r['file'])} | {r['tasks']} | {r['pass1']:.2f} | {r['pass_k'][-1]:.2f} | {100*r['mixed_task_share']:.0f}% | {r['test_retest_kappa']:.2f} | {r['agent_cost_usd_per_trial']:.3f} | {r['seconds_per_trial']:.0f} |")
g = lambda m, mode: rel[f"{m}_telecom_{mode}_gpt-4.1-2025-04-14_4trials.json"]["mixed_task_share"]
md += ["", "Simulated user as a variance source: tau2-bench's telecom `no-user` mode removes the user simulator (the agent acts alone). "
       f"For o4-mini the mixed-task share falls from {100*g('o4-mini-2025-04-16','default'):.0f}% to {100*g('o4-mini-2025-04-16','no-user'):.0f}%; "
       f"for gpt-4.1 it does not ({100*g('gpt-4.1-2025-04-14','default'):.0f}% to {100*g('gpt-4.1-2025-04-14','no-user'):.0f}%). "
       "No-user mode also changes the task, so this is suggestive, not a clean decomposition. The gate's answer to user-side noise is the same "
       "as to agent-side noise: repeat trials and pair by task.", ""]

# ---- rules
md += ["## 7. Do the trajectory rules mean anything?", "",
       "Over all default-mode trials, how often each rule fires and the failure rate with and without it. Rules explain failures in the PR comment; "
       "the verdict itself uses the task reward (final-state check).", "",
       "| rule | trials fired | of | fail rate when fired | fail rate otherwise |", "|---|---|---|---|---|"]
for r in d["rule_validity_default_mode_files"]:
    md.append(f"| {r['rule']} | {r['trials_fired']} | {r['trials']} | {100*r['fail_rate_when_fired']:.0f}% | {100*r['fail_rate_otherwise']:.0f}% |")
md += ["", "`write_without_confirmation` fires often but has the smallest lift: as a PR-comment signal it is weak, and its "
       "keyword matcher is the likely reason (users confirm in many ways). Human hand-off and step-budget rules carry real signal.", ""]

open(os.path.join(out, "SUMMARY.md"), "w").write("\n".join(md))
print("wrote", out)
